def parse_theme(text):
    bars = []
    for raw in text.split('|'):
        notes = []
        for token in raw.split():
            pitch, _, duration = token.partition(':')
            notes.append((None if pitch == '-' else int(pitch), int(duration or 2)))
        assert sum(length for _, length in notes) == 16, raw
        bars.append(notes)
    assert len(bars) == 4
    return bars

def scores():
    result = []
    for i, line in enumerate(SPECS.splitlines()):
        key, title, bpm, tonic, groove, duty, motif = line.split('|')
        themes = [parse_theme(theme) for theme in THEMES[key]]
        assert len(themes) == 3
        result.append(dict(id=key, title=title, bpm=int(bpm), tonic=int(tonic),
            key=['C','C#','D','Eb','E','F','F#','G','Ab','A','Bb','B'][int(tonic)%12]+' minor',
            mode='natural_minor', groove=groove, duty=float(duty), motif=motif,
            themes=themes, rank=i+1, threshold=(i+1)*4000))
    assert len(result) == 25
    assert len({str(s['themes']) for s in result}) == 25
    return result
